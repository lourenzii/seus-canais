function __i18nCompile() {
  if (__i18nCompiled) return __i18nCompiled;
  __i18nCompiled = I18N_RULES_EN.map(([pt, en]) => {
    if (pt instanceof RegExp) return { re: pt, en, lit: 999 };
    const toks = pt.split(/(\{\}|\{n\})/);
    let src = "^";
    let lit = 0;
    for (const t of toks) {
      if (t === "{}") src += "(.+?)";
      else if (t === "{n}") src += "(\\d[\\d.,]*)";
      else {
        src += t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        lit += t.length;
      }
    }
    return { re: new RegExp(src + "$"), en, lit };
  }).sort((a, b) => b.lit - a.lit);
  return __i18nCompiled;
}

function __i18nExact(v) {
  if (Object.prototype.hasOwnProperty.call(I18N_EN, v)) return I18N_EN[v];
  return v.split(", ").map((p) => (Object.prototype.hasOwnProperty.call(I18N_EN, p) ? I18N_EN[p] : p)).join(", ");
}

function uiLang(settings) {
  const s = (settings && settings.lang) || "auto";
  if (s === "pt" || s === "en") return s;
  let nav = "";
  try {
    nav = (navigator.language || "").toLowerCase();
  } catch (_) {}
  return nav.startsWith("pt") || !nav ? "pt" : "en";
}

function trText(s, lang, depth = 0) {
  if (lang !== "en" || typeof s !== "string" || !s || depth > 3) return s;
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  const lead = m[1], core = m[2], trail = m[3];
  if (!core) return s;
  if (Object.prototype.hasOwnProperty.call(I18N_EN, s)) return I18N_EN[s];
  if (Object.prototype.hasOwnProperty.call(I18N_EN, core)) return lead + I18N_EN[core] + trail;
  for (const { re, en } of __i18nCompile()) {
    const r = re.exec(core);
    if (r) {
      const out = typeof en === "function" ? en(r, (x) => trText(x, lang, depth + 1)) : en.replace(/\{([tr]?)(\d)\}/g, (_, t, i) => {
        const v = r[Number(i)] || "";
        if (t === "t") return __i18nExact(v);
        if (t === "r") return trText(v, lang, depth + 1);
        return v;
      });
      return lead + out + trail;
    }
  }
  if (core.includes(" · ")) {
    const parts = core.split(" · ");
    const tp = parts.map((p) => trText(p, lang, depth + 1));
    if (tp.some((p, i) => p !== parts[i])) return lead + tp.join(" · ") + trail;
  }
  return s;
}

